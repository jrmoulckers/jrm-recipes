function present(foodName: string): DietaryExpectedOutcome {
  return {
    finding: 'present',
    evidenceSource: 'food-link',
    foodIds: [foodNodeId(foodName)],
  };
}

function absent(foodName: string): DietaryExpectedOutcome {
  return {
    finding: 'absent',
    evidenceSource: 'food-link',
    foodIds: [foodNodeId(foodName)],
  };
}

function certifiedAbsent(foodName: string): DietaryExpectedOutcome {
  return {
    finding: 'absent',
    evidenceSource: 'certification',
    foodIds: [foodNodeId(foodName)],
  };
}

function textPresent(): DietaryExpectedOutcome {
  return { finding: 'present', evidenceSource: 'text-match' };
}

